import hashlib
import hmac
import json
from pathlib import Path
from tempfile import TemporaryDirectory

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from examples.ch23.authorization_service import AccessDenied,revoke_member,unit
from examples.ch26.integrations import (
    FIXTURE_KEYS,FIXTURE_NOW,Refused,handle_webhook,initialize as initialize_events,
    inventory as event_inventory,signature,
)
from examples.ch27.export_crypto import (
    CannotOpen,Keyring,create_export,initialize,inventory,read_export,rotate_export,
)

raw=(Path(__file__).parents[1]/"ch26/fixtures/report-ready.json").read_bytes()
changed=raw+b" "
secret=FIXTURE_KEYS["reports"]["old"]
stamp=str(FIXTURE_NOW)
original_tag=signature(secret,"reports",stamp,raw)
print("changed bytes, different digest:",hashlib.sha256(raw).digest()!=hashlib.sha256(changed).digest())
print("attacker can recompute unkeyed digest:",len(hashlib.sha256(changed).digest())==32)
print("old authenticated tag accepts changed bytes:",hmac.compare_digest(original_tag,signature(secret,"reports",stamp,changed)))

with TemporaryDirectory(prefix="casebook-crypto-") as folder:
    events=Path(folder)/"events.sqlite3"
    initialize_events(events)
    def deliver(body,kid,keys):
        tag=signature(FIXTURE_KEYS["reports"][kid],"reports",stamp,raw)
        return handle_webhook(events,partner_id="reports",raw=body,timestamp=stamp,key_id=kid,
                              supplied_signature=tag,keyrings=keys,now=FIXTURE_NOW)
    print("old-key delivery:",deliver(raw,"old",FIXTURE_KEYS)[0])
    saved=event_inventory(events)
    new_keys={"reports":{"new":FIXTURE_KEYS["reports"]["new"]}}
    for label,body,keys in (("changed body",changed,FIXTURE_KEYS),("retired key",raw,new_keys)):
        try:
            deliver(body,"old",keys)
        except Refused:
            print(label+": refused")
    print("new-key repeated event:",deliver(raw,"new",new_keys)[0])
    final=event_inventory(events)
    print("webhook state unchanged:",final==saved)
    print("receipt and report rows:",len(final["webhook_receipts"]),len(final["reports"]))

    database=Path(folder)/"casebook.sqlite3"
    initialize(database)
    # Fresh disposable dummy keys, generated by the maintained library. Never printed or persisted.
    old,new=AESGCM.generate_key(bit_length=256),AESGCM.generate_key(bit_length=256)
    original=Keyring({"export-old":old},"export-old")
    overlap=Keyring({"export-old":old,"export-new":new},"export-new")
    new_only=Keyring({"export-new":new},"export-new")
    export_id=create_export(database,user_id=1,workspace_id=1,note_ids=[101],keyring=original)
    plaintext=read_export(database,user_id=1,export_id=export_id,keyring=original)
    record=inventory(database)["encrypted_exports"][0]
    print("plaintext in stored ciphertext:",plaintext in record["ciphertext"])
    print("round trip workspace:",json.loads(plaintext)["workspace_id"])
    try:
        read_export(database,user_id=2,export_id=export_id,keyring=overlap)
    except AccessDenied:
        print("Ravi Alpha export: denied")
    with unit(database,write=True) as db:
        corrupted=bytes([record["ciphertext"][0]^1])+record["ciphertext"][1:]
        db.execute("UPDATE encrypted_exports SET ciphertext=? WHERE id=?",(corrupted,export_id))
    before=inventory(database)
    try:
        read_export(database,user_id=1,export_id=export_id,keyring=original)
    except CannotOpen:
        print("tampered record: refused")
    print("failed verification writes nothing:",inventory(database)==before)
    with unit(database,write=True) as db:
        db.execute("UPDATE encrypted_exports SET ciphertext=? WHERE id=?",(record["ciphertext"],export_id))
    rotate_export(database,export_id=export_id,keyring=overlap)
    migrated=inventory(database)["encrypted_exports"][0]
    print("rotated key and generation:",migrated["key_id"],migrated["generation"])
    print("new nonce:",migrated["nonce"]!=record["nonce"])
    print("same plaintext after old-key retirement:",read_export(database,user_id=1,export_id=export_id,keyring=new_only)==plaintext)
    revoke_member(database,actor_id=3,workspace_id=1,target_user_id=1)
    try:
        read_export(database,user_id=1,export_id=export_id,keyring=new_only)
    except AccessDenied:
        print("Mina after revocation: denied")
